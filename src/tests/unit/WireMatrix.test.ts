import {describe, it} from 'node:test'
import assert from 'node:assert/strict'
import {DBusBufferEncoder} from '../../lib/DBusBufferEncoder'
import {DBusBufferDecoder} from '../../lib/DBusBufferDecoder'
import {DBusMessageEndianness} from '../../lib/enums/DBusMessageEndianness'
import {alternativeInputForms, InputForm, loadWireMatrix, MatrixCase, toExpected, toInput, WireMatrix} from '../helpers/TaggedValue'
import {knownFailure, MatrixCheck} from '../fixtures/KnownFailures'
import {knownBug} from '../helpers/KnownBug'
import {DecodeOpts} from '../../types/DecodeOpts'
import {DBusSignedValue} from '../../lib/DBusSignedValue'

const matrix: WireMatrix = loadWireMatrix()

const BYTE_ORDERS: [string, DBusMessageEndianness, 'le' | 'be'][] = [
    ['little-endian', DBusMessageEndianness.LE, 'le'],
    ['big-endian', DBusMessageEndianness.BE, 'be']
]

function options(testCase: MatrixCase, check: MatrixCheck): { todo?: string } {
    const reason: string | undefined = knownFailure(testCase.id, check)
    return reason ? knownBug(reason) : {}
}

function encode(testCase: MatrixCase, endianness: DBusMessageEndianness, form?: InputForm): string {
    const args: any[] = toInput(testCase.args, form)
    return new DBusBufferEncoder(endianness).encode(testCase.signature, args.length > 1 ? args : args[0]).toString('hex')
}

/**
 * Reference vectors generated by GDBus (see src/tests/fixtures/gdbus/generate.py): every basic type with boundary
 * values, every basic type inside arrays, dictionaries (as key and value), structs and variants, the same forms at
 * every starting offset modulo 8, nested containers, the specification's nesting limits and variant type inference.
 * Each case is encoded and decoded in both byte orders, and encoded once more for each alternative input form.
 */
describe(`wire format matrix (${matrix.generator})`, (): void => {
    const categories: string[] = [...new Set(matrix.cases.map((testCase: MatrixCase): string => testCase.category))]
    for (const category of categories) {
        describe(category, (): void => {
            for (const testCase of matrix.cases.filter((item: MatrixCase): boolean => item.category === category)) {
                describe(testCase.id, (): void => {
                    for (const [name, endianness, field] of BYTE_ORDERS) {
                        it(`encodes ${name}`, options(testCase, `encode ${field}`), (): void => {
                            assert.equal(encode(testCase, endianness), testCase[field])
                        })
                    }
                    for (const [formName, form] of alternativeInputForms(testCase.args)) {
                        it(`encodes with ${formName}`, options(testCase, `encode ${formName}`), (): void => {
                            assert.equal(encode(testCase, DBusMessageEndianness.LE, form), testCase.le)
                        })
                    }
                    for (const [name, endianness, field] of BYTE_ORDERS) {
                        it(`decodes ${name}`, options(testCase, `decode ${field}`), (): void => {
                            const decoded: any[] = new DBusBufferDecoder(endianness, Buffer.from(testCase[field], 'hex')).decode(testCase.signature)
                            assert.deepEqual(decoded, toExpected(testCase.args))
                        })
                    }
                })
            }
        })
    }
})

/**
 * What is received can be sent again unchanged: for every case of the matrix, the values decoded from GDBus's bytes,
 * in every decoding mode, encode to the same bytes. With types 'none' this relies on the signatures recorded for
 * values that came in variants; with 'variants' and 'all' the values carry their types.
 */
describe(`re-encoding decoded values (${matrix.generator})`, (): void => {
    // Objects list integer-like property names in ascending order first, whatever the order they were added in, so
    // these dictionaries come back with their entries reordered (the same entries; Maps keep the order)
    const reorderedAsObjects: string[] = ['dict: a{ns}', 'dict: a{is}']
    const modes: [string, DecodeOpts, string[]][] = [
        ['plain values', {}, reorderedAsObjects],
        ['types variants', {types: 'variants'}, reorderedAsObjects],
        ['types all', {types: 'all'}, []],
        ['dictionaries as Maps', {dictionaries: 'map'}, []],
        ['plain values with 64-bit integers as numbers', {int64: 'number'}, reorderedAsObjects]
    ]
    for (const [name, opts, expected] of modes) {
        it(`gives the original bytes back from ${name}`, (): void => {
            const mismatches: string[] = []
            for (const testCase of matrix.cases) {
                const decoded: any[] = new DBusBufferDecoder(DBusMessageEndianness.LE, Buffer.from(testCase.le, 'hex')).decode(testCase.signature, opts)
                let encoded: string
                try {
                    // As a message body is encoded: the arguments list, or its only value
                    encoded = new DBusBufferEncoder().encode(testCase.signature, DBusSignedValue.bodyValue(testCase.signature, decoded)).toString('hex')
                } catch (error) {
                    encoded = `throws ${(error as Error).message}`
                }
                if (encoded !== testCase.le) mismatches.push(testCase.id)
            }
            assert.deepEqual(mismatches, expected)
        })
    }
})
